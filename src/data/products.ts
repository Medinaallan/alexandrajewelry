export const getFeaturedProducts = () => products.filter((p) => p.featured && p.active);
export const getNewProducts = () => products.filter((p) => p.isNew && p.active);
export const getSaleProducts = () => products.filter((p) => p.onSale && p.active);
export const getProductBySlug = (slug: string) => products.find((p) => p.slug === slug);
export const getProductsByCategory = (categoryId: string) =>
  products.filter((p) => p.categoryId === categoryId && p.active);
export const getRelatedProducts = (product: Product, limit = 4) =>
  products.filter((p) => p.categoryId === product.categoryId && p.id !== product.id && p.active).slice(0, limit);
